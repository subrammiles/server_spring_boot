-- Flyway runs V1, V2, ... in order, ONCE each, and records them in flyway_schema_history.
-- Never edit a migration that has run in production: add a new V3__... instead.
-- Written in standard SQL so it runs on both H2 (dev/tests) and PostgreSQL (prod, Testcontainers test).

CREATE TABLE course (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    version     BIGINT NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE,
    updated_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE review (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating      INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    description VARCHAR(500),
    course_id   BIGINT NOT NULL REFERENCES course (id),
    version     BIGINT NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE,
    updated_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE passport (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number      VARCHAR(20) NOT NULL UNIQUE,
    version     BIGINT NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE,
    updated_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE student (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    passport_id BIGINT NOT NULL UNIQUE REFERENCES passport (id),
    version     BIGINT NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE,
    updated_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE student_course (
    student_id  BIGINT NOT NULL REFERENCES student (id),
    course_id   BIGINT NOT NULL REFERENCES course (id),
    PRIMARY KEY (student_id, course_id)
);

CREATE TABLE employee (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_type VARCHAR(31) NOT NULL,
    name          VARCHAR(100) NOT NULL,
    salary        NUMERIC(38, 2),
    hourly_wage   NUMERIC(38, 2),
    version       BIGINT NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE,
    updated_at    TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_review_course ON review (course_id);
